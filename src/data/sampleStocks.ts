export function getStocksByMarket(market: Market): StockFundamentals[] {
  return SAMPLE_STOCKS.filter((s) => s.market === market);
}

export function findStock(symbol: string): StockFundamentals | undefined {
  const key = symbol.trim().toUpperCase();
  return SAMPLE_STOCKS.find((s) => s.symbol.toUpperCase() === key);
}

export function getSamplePriceHistory(symbol: string): PriceBar[] {
  const base = findStock(symbol)?.price ?? 100;
  const bars: PriceBar[] = [];
  for (let i = 60; i >= 0; i--) {
    const drift = (60 - i) * 0.05;
    const noise = Math.sin(i * 0.4) * 2;
    const close = base - drift + noise;
    bars.push({
      date: new Date(Date.now() - i * 86400000).toISOString().slice(0, 10),
      open: close - 0.5,
      high: close + 1.2,
      low: close - 1.2,
      close,
      volume: 1_000_000 + i * 10_000,
    });
  }
  return bars;
}
